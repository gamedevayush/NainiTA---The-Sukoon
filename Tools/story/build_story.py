"""Builds the story's scenes (owner, 26 Nov 2026: the bible's missions, Hindi text + AI voice; docs/STORY.md).

Input : Tools/story/scenes/*.json - a scene as Story/Cutscene.cs reads it, plus "hi" (the Hindi, Devanagari) next to every
        text ("key" = the Hinglish, "en" = the English) and "nameHi" / "playerHi" for the names.
        Tools/story/cast.json - the voice of each character (edge-tts: voice, pitch, rate); "player" = nikhil.
        Tools/story/strings_missions.tsv - mission titles, objectives (key <TAB> en <TAB> hi).
Output: Assets/Resources/Story/<id>.json                 (the scene, "hi" taken out, "voice" filled in)
        Assets/Resources/Voices/Story/<id>/<nn>.mp3      (one per spoken line; only lines whose text / voice changed)
        Tools/loc/strings_story.tsv                      (the block after the marker line is rewritten)
        then Tools/loc/build_loc.py (the Hindi shaped for the game's font) unless --no-loc.

Run: python Tools/story/build_story.py [--no-loc] [--no-voice]     (needs: pip install --user edge-tts)
Narrator lines (who "") and lines with "voice": "none" are not voiced.
"""
import asyncio, glob, hashlib, json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HERE = os.path.dirname(os.path.abspath(__file__))
SCENES = os.path.join(HERE, "scenes")
OUT_SCENES = os.path.join(ROOT, "Assets", "Resources", "Story")
OUT_VOICES = os.path.join(ROOT, "Assets", "Resources", "Voices", "Story")
TSV = os.path.join(ROOT, "Tools", "loc", "strings_story.tsv")
MANIFEST = os.path.join(HERE, "voices_manifest.json")
MARK = "# --- story scenes and missions (generated by Tools/story/build_story.py; edit Tools/story, not here) ---"


def tts(text, who, cast, path):
    import edge_tts
    c = cast[who]
    async def go():
        await edge_tts.Communicate(text, c["voice"], rate=c.get("rate", "+0%"), pitch=c.get("pitch", "+0Hz")).save(path)
    for attempt in range(3):
        try:
            asyncio.run(go())
            if os.path.getsize(path) > 1000:
                return
        except Exception as e:
            print("  tts retry", attempt + 1, who, e)
    sys.exit("tts failed: " + path)


def main():
    no_loc = "--no-loc" in sys.argv
    no_voice = "--no-voice" in sys.argv
    cast = json.load(open(os.path.join(HERE, "cast.json"), encoding="utf-8"))
    manifest = json.load(open(MANIFEST, encoding="utf-8")) if os.path.exists(MANIFEST) else {}
    rows, seen = [], {}

    def row(key, en, hi, where):
        if not key or hi is None:
            return
        for f in (key, en, hi):
            if "\t" in f or "#" in f:
                sys.exit(f"{where}: a tab or '#' in text (the loc table uses them): {f}")
        if key in seen and seen[key] != (en, hi):
            print(f"  note: '{key}' has two translations; the first is kept ({where})")
            return
        if key not in seen:
            seen[key] = (en, hi)
            rows.append((key, en, hi))

    os.makedirs(OUT_SCENES, exist_ok=True)
    made = 0
    for path in sorted(glob.glob(os.path.join(SCENES, "*.json"))):
        sc = json.load(open(path, encoding="utf-8"))
        sid = sc["id"]
        where = os.path.basename(path)
        if "playerHi" in sc:
            row(sc.get("playerKey", "Tum"), sc.get("playerEn", "You"), sc.pop("playerHi"), where)
        for a in sc.get("actors", []):
            if "nameHi" in a:
                row(a.get("nameKey"), a.get("nameEn", a.get("nameKey")), a.pop("nameHi"), where)
        n = 0
        for i, st in enumerate(sc.get("steps", [])):
            op = st.get("op")
            hi = st.pop("hi", None)
            if hi is not None:
                row(st.get("key"), st.get("en", st.get("key")), hi, f"{where} step {i}")
            for o in st.get("opts", []) or []:
                ohi = o.pop("hi", None)
                if ohi is not None:
                    row(o.get("key"), o.get("en", o.get("key")), ohi, f"{where} step {i} option")
            if op == "say":
                who = st.get("who", "")
                if who == "player":
                    who = "nikhil"
                if who and st.get("voice") != "none" and hi:
                    if who not in cast:
                        sys.exit(f"{where} step {i}: no voice for '{who}' in cast.json")
                    n += 1
                    rel = f"Voices/Story/{sid}/{n:02d}"
                    st["voice"] = rel
                    mp3 = os.path.join(ROOT, "Assets", "Resources", rel.replace("/", os.sep) + ".mp3")
                    sig = hashlib.sha1(json.dumps([hi, cast[who]], ensure_ascii=False).encode("utf-8")).hexdigest()
                    if not no_voice and (manifest.get(rel) != sig or not os.path.exists(mp3)):
                        os.makedirs(os.path.dirname(mp3), exist_ok=True)
                        print(f"  voice {rel}  ({who}) {hi}")
                        tts(hi, who, cast, mp3)
                        manifest[rel] = sig
                        made += 1
                elif st.get("voice") == "none":
                    st.pop("voice")
        out = os.path.join(OUT_SCENES, sid + ".json")
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            json.dump(sc, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"scene {sid}: {len(sc.get('steps', []))} steps, {n} voiced lines -> {os.path.relpath(out, ROOT)}")

    extra = os.path.join(HERE, "strings_missions.tsv")
    if os.path.exists(extra):
        for ln in open(extra, encoding="utf-8"):
            ln = ln.rstrip("\n")
            if not ln or ln.startswith("#"):
                continue
            p = ln.split("\t")
            if len(p) >= 3:
                row(p[0], p[1], p[2], "strings_missions.tsv")

    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=1, sort_keys=True)

    # the loc table: everything up to the marker stays (hand-written rows), the rest is ours
    head = []
    if os.path.exists(TSV):
        for ln in open(TSV, encoding="utf-8"):
            if ln.rstrip("\n") == MARK:
                break
            head.append(ln.rstrip("\n"))
    hand = {ln.split("\t")[0] for ln in head if ln and not ln.startswith("#")}
    with open(TSV, "w", encoding="utf-8", newline="\n") as f:
        for ln in head:
            f.write(ln + "\n")
        f.write(MARK + "\n")
        for k, en, hi in rows:
            if k in hand:
                continue
            f.write(f"{k}\t{en}\t{hi}\n")
    print(f"{len(rows)} text rows -> {os.path.relpath(TSV, ROOT)}; {made} new voice files")

    if not no_loc:
        r = subprocess.run([sys.executable, os.path.join(ROOT, "Tools", "loc", "build_loc.py")], cwd=ROOT)
        if r.returncode != 0:
            sys.exit("build_loc.py failed")


if __name__ == "__main__":
    main()
